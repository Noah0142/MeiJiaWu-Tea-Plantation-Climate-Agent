# -*- coding: utf-8 -*-
"""score2.py — 2 分钟介绍片的声音: 一间大房间里的环境床 + 事件, 与画面同拍

床(原创合成, 无第三方曲目): 每章一次 sub+air 的缓慢呼吸, 章节切换处一次落点;
事件: 与 comp2.html 的画面节拍逐一对齐(逐块出现的图解、逐张进位的图层卡、镜头落点)。
旁白由 final_mix.py 叠在上面(并把床压下去)。输出 bed.wav
"""
import json
import math
import os
import pathlib
import sys

ONETAKE = os.environ.get("ONETAKE_DIR", r"C:\Users\Noah1\AppData\Local\Temp\onetake")
sys.path.insert(0, str(pathlib.Path(ONETAKE) / "scripts"))
import numpy as np                                          # noqa: E402
from sfx_palette import Score, air, glass, wood, sub, bubble, wobble   # noqa: E402

HERE = pathlib.Path(__file__).parent
NARR = json.loads((HERE / "assets" / "narration.js").read_text(encoding="utf-8")
                  .replace("window.NARR = ", "").rstrip(";\n"))
DUR = NARR["total"] + 5.6
C = NARR["chapters"]
rng = np.random.default_rng(23)
s = Score(dur=DUR, T60=1.5)
place = s.place

# ── 环境床: 章节的呼吸 ────────────────────────────────────────────────
for i, c in enumerate(C):
    place(sub(44 + i * 2, 5.0), c["t"], 0.11, 0.0, 0.55)
    place(air(2.6, 170 + i * 20, 900, 3.2), c["t"], 0.085, 0.0, 0.6)
# 每 12 秒一颗很轻的"钟"(玻璃), 让长片有脉搏
tt = 6.0
while tt < DUR - 2:
    place(glass(523 * (1 + (int(tt / 12) % 3) * 0.25), 1.4, 0.5), tt, 0.045, rng.uniform(-0.2, 0.2), 0.6)
    tt += 12
# ── 章节切换的落点 ────────────────────────────────────────────────────
for c in C[1:]:
    place(air(0.6, 220, 1500, 0.9), c["t"] - 1.4, 0.26, 0.0, 0.5)
    place(sub(58 - C.index(c), 0.7), c["t"] - 1.3, 0.20)

# ── 片头: 横断面画过地形 ──────────────────────────────────────────────
place(wood(150, 0.07), C[0]["t"] + 1.0, 0.28, -0.4, 0.2)
place(air(1.1, 700, 2400, 1.0), C[0]["t"] + 1.05, 0.28, -0.5, 0.45, pan_to=0.5)
place(bubble(520, 0.2), C[0]["t"] + 4.2, 0.24, 0.4, 0.3)

# ── 大盘: 曲线卡 / 区间 / 风险卡 ──────────────────────────────────────
place(glass(784, 0.9, 0.6), C[1]["t"] + 3.3, 0.14, -0.2, 0.5)
place(air(0.5, 300, 2200, 0.8), C[1]["t"] + 8.0, 0.28, -0.3, 0.5, pan_to=0.5)
place(glass(1174, 1.1, 0.45), C[1]["t"] + 14.0, 0.13, 0.3, 0.6)
place(wood(210, 0.08), C[1]["t"] + 15.8, 0.22, 0.3, 0.2)
place(sub(70, 0.5), C[1]["t"] + 15.9, 0.16)

# ── 农事对话: 点击 + 回答 ─────────────────────────────────────────────
place(wood(200, 0.08), C[2]["t"] + 2.6, 0.26, -0.1, 0.2)
place(bubble(600, 0.22), C[2]["t"] + 3.0, 0.22, 0.0, 0.35)
place(glass(990, 0.9, 0.45), C[2]["t"] + 3.2, 0.13, 0.0, 0.55)

# ── 地形图选点: 点位环 / 面板 / 六张图层 ──────────────────────────────
place(bubble(440, 0.22), C[3]["t"] + 1.2, 0.22, -0.3, 0.3)
for i in range(6):
    place(glass(659 + i * 110, 0.7, 0.5), C[3]["t"] + 10.4 + i * 0.14, 0.11, -0.5 + i * 0.2, 0.45)
place(air(0.6, 260, 1800, 0.8), C[3]["t"] + 10.6, 0.24, 0.0, 0.5)

# ── 模型图解: 逐块落下 ────────────────────────────────────────────────
for tt, f in [(77.7, 340), (77.9, 420), (78.1, 500), (81.7, 300), (86.3, 240),
              (91.1, 380), (91.25, 440), (91.4, 520), (95.7, 360), (95.85, 400), (96.0, 460), (96.15, 520)]:
    place(wood(f, 0.08), tt, 0.17, rng.uniform(-0.35, 0.35), 0.25)
place(air(0.7, 200, 1600, 1.0), 86.1, 0.26, 0.0, 0.5)
place(air(0.5, 240, 1400, 0.8), 91.0, 0.22, 0.0, 0.5)
for i, f in enumerate([523, 659, 784, 988]):
    place(glass(f, 0.9, 0.45), 95.7 + i * 0.15, 0.12, -0.3 + i * 0.2, 0.5)
place(sub(52, 1.0), 95.9, 0.18)

# ── 传感器与手机 ──────────────────────────────────────────────────────
place(bubble(470, 0.22), C[5]["t"] + 0.5, 0.20, -0.3, 0.3)
for i in range(3):
    place(glass(659 + i * 130, 0.7, 0.4), C[5]["t"] + 5.3 + i * 0.25, 0.10, 0.2 + i * 0.25, 0.4)

# ── 落版 ──────────────────────────────────────────────────────────────
t7 = C[6]["t"]
place(air(0.9, 160, 1200, 0.9), t7 - 1.8, 0.34, 0.0, 0.6)
place(sub(48, 1.2), t7 - 1.6, 0.26)
place(glass(392, 1.6, 0.35), t7 - 0.5, 0.15, 0.0, 0.7)
place(glass(523, 1.8, 0.3), t7 + 0.5, 0.11, 0.0, 0.7)
place(sub(44, 2.2), t7 + 2.4, 0.30)

s.write(str(HERE / "bed.wav"))
